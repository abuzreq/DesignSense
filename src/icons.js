// Vuetify resolves its own icons ($expand, $checkboxOn...) to path data
// before they reach MdiIcon, so a path passes through as it is.
const PATH = /^[mzlhvcsqta]\s*[-+.0-9]/i;

/** The SVG path for an icon name, or the path itself; "" when unknown. */
export function iconPath(icon) {
  if (Object.prototype.hasOwnProperty.call(ICONS, icon)) return ICONS[icon];
  if (PATH.test(icon)) return icon;
  if (process.env.NODE_ENV !== "production") {
    console.warn('No icon named "' + icon + '"; add it to src/icons.js.');
  }
  return "";
}
